-- Darth Beer.com データ修正
-- 目的     : (1) 重複スタイル st0025 の明示  (2) 総称スタイルの基準IBU を NULL にする
-- 対象DB   : dev = beer_dev / 本番昇格時 = beer
-- 種別     : DML のみ (DDL を含まない)
-- 冪等性   : deploy/apply_sql.php が schema_migrations(filename + sha256)で二重適用を防ぐ。
--            適用済みのこのファイルは書き換えないこと。直すときは新しい番号のファイルを作る。
-- 巻き戻し : 012_style_meta_20260830_rollback.sql
-- 適用     : remote_sql.sh dev --apply <このファイル> --dry-run  で件数を確認してから本適用
--
-- なぜ 011 と分けるか:
--   011 は解説文の追加、こちらは分類と数値の修正で、取り消したくなる単位が違う。

-- ------------------------------------------------------------------
-- (1) st0025「German-Style Hefeweizen」は st0100「Hefe Weizen」と実質同一
-- ------------------------------------------------------------------
-- 監査で、両者の主要な事実要素(バイエルン発祥 / ヴァイツェン酵母のバナナ・クローブ香 /
-- 「ヘフェ」=酵母 / 非ろ過の白濁 / 控えめな苦味)がほぼ完全に重複することが確認された。
-- 銘柄が紐づいているのは st0100 のみ(4件)で、st0025 は0件。
--
-- **削除ではなく改名する。** IDは再利用しない規則 (db/README.md) を守るため。
-- 先に st0019「New England IPA」に対して 009 で行ったのと同じ処理。
-- 今回のバッチ (011) では st0025 に解説を書いていない —— 書くと同じ説明が2ページ並ぶため。
UPDATE `style` SET `StyleName` = 'Hefeweizen (未使用・st0100と重複)' WHERE `StyleID` = 'st0025';

-- ------------------------------------------------------------------
-- (2) 総称スタイルの基準IBU を NULL にする
-- ------------------------------------------------------------------
-- style.IBU は飾りではなく、**銘柄の IBU が未計測のときの推定の根拠**である
-- (規律 §6 の根拠1)。ここに置いた数値は、そのスタイルに銘柄が付いた瞬間に
-- その銘柄の苦味として画面に出て、estimated_fields に 'IBU_all' と記録される。
--
-- st0080 Session Beer と st0082 Specialty Beer は、ベースになるビールが定まらない総称で、
-- 代表値が存在しない。セッションIPA とセッションスタウトでは苦味がまるで違い、
-- Specialty Beer に至っては「他の分類が拾わないもの全部」である。
-- 加えて st0082 の 50.500 は st0077 Honey Beer と完全に一致しており(他に 50.5 は無い)、
-- 入力時の取り違えの形をしている。
--
-- 先行例: st0107 Barrel-Aged Beer は、同じ理由で基準IBU を最初から NULL にしてある
--         (苦味の型ではなく工程の分類だから)。それに揃える。
--
-- 現在この2スタイルに紐づく銘柄は0件なので、この変更で表示が変わる銘柄は無い。
UPDATE `style` SET `IBU` = NULL WHERE `StyleID` IN ('st0080', 'st0082');
